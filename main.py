# -*- coding: utf-8 -*-
"""
🍗 갓슴살 AI 코치 (Gatseumsal AI Coach)
----------------------------------------
운동 기록을 입력하면, 닭가슴살 캐릭터가 약점을 분석해서
열혈 츤데레 스타일로 코멘트해주는 프로그램.

- 만든 사람: (이름 적기)
- 사용 기술: Python
- 핵심 기능: 운동 기록 분석 → 약점(가장 적게 한 운동 분류) 찾기 → 캐릭터 코멘트
"""

import os
import sys

import anthropic

# 윈도우 화면에서도 한글·이모지가 깨지지 않게 출력 방식을 UTF-8로 맞춤
sys.stdout.reconfigure(encoding="utf-8")


# ──────────────────────────────────────────────
# 1) 운동 기록 데이터 (예시)
#    실제 앱에서는 사용자가 입력하지만, 지금은 샘플로 동작 확인
# ──────────────────────────────────────────────
운동기록 = [
    {"동작": "풀업",      "분류": "맨몸",   "값": 30, "단위": "회"},
    {"동작": "푸시업",    "분류": "맨몸",   "값": 50, "단위": "회"},
    {"동작": "데드리프트", "분류": "바벨",   "값": 100, "단위": "kg"},
    {"동작": "스쿼트",    "분류": "바벨",   "값": 80, "단위": "kg"},
    {"동작": "러닝",      "분류": "유산소", "값": 2000, "단위": "m"},
]


# ──────────────────────────────────────────────
# 2) 이름 호칭 만들기 (받침 있으면 '아', 없으면 '야')
#    예) 주한 → 주한아 / 민지 → 민지야
# ──────────────────────────────────────────────
def 호칭_만들기(이름):
    마지막글자 = 이름[-1]
    코드 = ord(마지막글자)
    # 한글 범위 안에서 받침(종성) 여부 계산
    if 0xAC00 <= 코드 <= 0xD7A3:
        받침 = (코드 - 0xAC00) % 28
        return 이름 + ("아" if 받침 != 0 else "야")
    # 한글이 아니면(영어 닉네임 등) 그냥 이름만
    return 이름


# ──────────────────────────────────────────────
# 3) 약점 분석: 분류별로 몇 번 했는지 세고, 가장 적게 한 분류를 찾음
# ──────────────────────────────────────────────
def 약점_분석(기록):
    분류_횟수 = {}
    for 항목 in 기록:
        분류 = 항목["분류"]
        분류_횟수[분류] = 분류_횟수.get(분류, 0) + 1

    가장_많은 = max(분류_횟수, key=분류_횟수.get)
    가장_적은 = min(분류_횟수, key=분류_횟수.get)
    return 분류_횟수, 가장_많은, 가장_적은


# ──────────────────────────────────────────────
# 4) 캐릭터 코멘트: 약점에 맞춰 열혈 츤데레 한마디
# ──────────────────────────────────────────────
def 캐릭터_코멘트(이름, 가장_많은, 가장_적은, 총개수):
    부름 = 호칭_만들기(이름)
    코멘트_사전 = {
        "맨몸":   "맨몸 운동은 충분해! 근데 무게도 좀 들어야 진짜 갓슴살 되는 거 알지?",
        "바벨":   "바벨은 잘 치네... 칭찬은 아니고 그냥 사실 말한 거야. 유산소도 좀 해!",
        "덤벨":   "덤벨만 좋아하지 말고 골고루 좀 하자, 응?",
        "유산소": "심장은 단련됐겠다. 근데 근력도 키워야 균형 잡힌 갓슴살이지!",
        "기타":   "이것저것 하는 건 좋은데, 기본기도 챙기자!",
    }
    약점_멘트 = 코멘트_사전.get(가장_적은, "골고루 더 해보자!")
    return (
        f"\"{부름}, 오늘 운동 {총개수}개나 했네! 👀\n"
        f"  근데 '{가장_적은}' 운동이 제일 부족해. {약점_멘트}\n"
        f"  '{가장_많은}'은(는) 잘하고 있으니까... 흥, 계속 그렇게 해.\""
    )


# ──────────────────────────────────────────────
# 4-2) 🤖 진짜 AI(Claude)로 캐릭터 코멘트 만들기
#      ANTHROPIC_API_KEY 환경변수가 있으면 AI가 코멘트를 생성하고,
#      없으면 위의 규칙기반(캐릭터_코멘트) 함수를 대신 사용함.
# ──────────────────────────────────────────────
def 캐릭터_코멘트_AI(이름, 분류_횟수, 가장_많은, 가장_적은, 운동기록):
    부름 = 호칭_만들기(이름)

    # 운동 기록을 AI가 읽기 쉬운 글로 정리
    운동_요약 = ", ".join(
        f"{항목['동작']}({항목['분류']}) {항목['값']}{항목['단위']}" for 항목 in 운동기록
    )

    # 캐릭터의 성격·역할을 정해주는 지시문(system prompt)
    캐릭터_설정 = (
        "너는 '갓슴살'이라는 운동 앱의 닭가슴살 캐릭터야. "
        "사용자의 분신이고, 운동 기록을 보고 약점을 짚어주는 열혈 츤데레 코치야. "
        "말투는 무뚝뚝하지만 속으로는 응원하는 귀여운 츤데레. "
        "한국어로, 2~3문장으로 짧게 코멘트해. 이모지는 1개까지만."
    )

    # 이번 요청에 줄 실제 정보(user 메시지)
    질문 = (
        f"사용자 이름(부를 때): {부름}\n"
        f"오늘 한 운동: {운동_요약}\n"
        f"분류별 횟수: {분류_횟수}\n"
        f"제일 많이 한 분류: {가장_많은} / 제일 부족한 분류: {가장_적은}\n\n"
        f"위 기록을 보고 {부름}에게 약점을 짚어주며 츤데레로 한마디 해줘."
    )

    client = anthropic.Anthropic()  # 키는 환경변수 ANTHROPIC_API_KEY에서 자동으로 읽음
    응답 = client.messages.create(
        model="claude-opus-4-8",
        max_tokens=300,
        system=캐릭터_설정,
        messages=[{"role": "user", "content": 질문}],
    )

    # 응답에서 글자(text)만 뽑아서 합치기
    return "".join(블록.text for 블록 in 응답.content if 블록.type == "text")


# ──────────────────────────────────────────────
# 5) 프로그램 실행
# ──────────────────────────────────────────────
def main():
    이름 = "주한"  # 나중에 input()으로 사용자가 입력하게 바꿀 수 있음

    print("=" * 45)
    print("🍗 갓슴살 AI 코치 — 오늘의 운동 분석")
    print("=" * 45)

    # 오늘 한 운동 보여주기
    print("\n[오늘 한 운동]")
    for 항목 in 운동기록:
        print(f"  - {항목['동작']}({항목['분류']}): {항목['값']}{항목['단위']}")

    # 분석
    분류_횟수, 가장_많은, 가장_적은 = 약점_분석(운동기록)

    print("\n[분류별 운동 횟수]")
    for 분류, 횟수 in 분류_횟수.items():
        막대 = "■" * 횟수
        print(f"  {분류:4s} | {막대} {횟수}개")

    # 캐릭터 코멘트
    print("\n[🍗 닭가슴살 코치의 한마디]")
    if os.environ.get("ANTHROPIC_API_KEY"):
        # API 키가 있으면 → 진짜 AI(Claude)가 코멘트 생성
        print("  (🤖 AI가 코멘트를 생각하는 중...)\n")
        코멘트 = 캐릭터_코멘트_AI(이름, 분류_횟수, 가장_많은, 가장_적은, 운동기록)
    else:
        # 키가 없으면 → 규칙기반 코멘트로 대체
        코멘트 = 캐릭터_코멘트(이름, 가장_많은, 가장_적은, len(운동기록))
    print(코멘트)
    print()


if __name__ == "__main__":
    main()
